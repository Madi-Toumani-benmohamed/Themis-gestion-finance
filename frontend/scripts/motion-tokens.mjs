import { readFile, writeFile } from 'node:fs/promises'
import { timing, ease } from '../src/motion/tokens.js'

// Static CSS available before React; no runtime reads or style injection.
const target = new URL('../src/motion/tokens.css', import.meta.url)
const css = `/* Generated by npm run tokens:generate from motion/tokens.js. Do not edit. */\n:root {\n  --motion-ease: cubic-bezier(${ease.join(', ')});\n${Object.entries(timing).map(([name, seconds]) => `  --motion-${name}: ${Math.round(seconds * 1000)}ms;`).join('\n')}\n}\n`
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== css) throw new Error('Motion CSS is stale. Run npm run tokens:generate.')
} else {
  await writeFile(target, css)
}
